
USE ROLE AI_DWH_ROLE;
USE WAREHOUSE AI_DWH_WH;
USE DATABASE AI_DWH;

-- Project schemas
CREATE SCHEMA IF NOT EXISTS CANADA_EMP_RAW;
CREATE SCHEMA IF NOT EXISTS CANADA_EMP_STAGING;
CREATE SCHEMA IF NOT EXISTS CANADA_EMP_MARTS;

-- CSV file format
CREATE FILE FORMAT IF NOT EXISTS CANADA_EMP_RAW.STATCAN_CSV_FORMAT
    TYPE = CSV
    SKIP_BLANK_LINES = TRUE
    FIELD_DELIMITER = ','
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    SKIP_HEADER = 1
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = ('', 'NULL');

-- Internal stage
CREATE STAGE IF NOT EXISTS CANADA_EMP_RAW.STATCAN_STAGE
    FILE_FORMAT = CANADA_EMP_RAW.STATCAN_CSV_FORMAT;

-- Verify
SHOW SCHEMAS LIKE 'CANADA_EMP_%' IN DATABASE AI_DWH;
SHOW STAGES IN SCHEMA AI_DWH.CANADA_EMP_RAW;

