
USE ROLE AI_DWH_ROLE;
USE WAREHOUSE AI_DWH_WH;
USE DATABASE AI_DWH;
USE SCHEMA CANADA_EMP_RAW;

CREATE TABLE IF NOT EXISTS EMPLOYMENT_RAW (
    REF_DATE VARCHAR,
    GEO VARCHAR,
    DGUID VARCHAR,
    LABOUR_FORCE_CHARACTERISTICS VARCHAR,
    GENDER VARCHAR,
    AGE_GROUP VARCHAR,
    STATISTICS VARCHAR,
    DATA_TYPE VARCHAR,
    UOM VARCHAR,
    UOM_ID VARCHAR,
    SCALAR_FACTOR VARCHAR,
    SCALAR_ID VARCHAR,
    VECTOR VARCHAR,
    COORDINATE VARCHAR,
    VALUE FLOAT,
    STATUS VARCHAR,
    SYMBOL VARCHAR,
    TERMINATED VARCHAR,
    DECIMALS VARCHAR
);


-- Load all three provincial CSV files
COPY INTO AI_DWH.CANADA_EMP_RAW.EMPLOYMENT_RAW
FROM @AI_DWH.CANADA_EMP_RAW.STATCAN_STAGE
FILE_FORMAT = (
    FORMAT_NAME = 'AI_DWH.CANADA_EMP_RAW.STATCAN_CSV_FORMAT'
)
ON_ERROR = ABORT_STATEMENT;

-- Validate records by province
SELECT
    GEO,
    COUNT(*) AS ROW_COUNT,
    MIN(REF_DATE) AS FIRST_MONTH,
    MAX(REF_DATE) AS LAST_MONTH
FROM AI_DWH.CANADA_EMP_RAW.EMPLOYMENT_RAW
GROUP BY GEO
ORDER BY GEO;
